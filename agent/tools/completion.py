"""The ``complete_inspection`` agent tool (Task 6.7).

The last of the seven constrained Agent_Tools (design.md "The Seven Agent
Tools"). Where ``analyze_frame`` / ``analyze_region`` *perceive* and
``save_inspection_finding`` / ``request_human_review`` *persist*,
``complete_inspection`` **finalizes**: it terminates the Agent_Loop, assembles
the structured :class:`InspectionReport`, and persists finalization so the
report is retrievable by inspection id.

Design mapping ("The Seven Agent Tools" table)
----------------------------------------------

| Tool                 | Input          | Output                                 | Failure behavior                               |
| ``complete_inspection`` | inspection id  | ``InspectionReport`` persisted + trace persisted | if no findings/escalations -> report records zero findings (12.3) |

Requirements wired here
-----------------------

* **12.1 - finalize + generate the report.** :func:`complete_inspection` marks
  the inspection ``status="completed"`` with its loop ``stop_reason`` and
  progress ``100`` (via :meth:`~agent.store.Store.put_inspection`), then builds
  an :class:`InspectionReport` from the store's persisted state. The report
  contains each :class:`~agent.store.InspectionFinding` -- hazard type, evidence
  reference, confidence, source timestamp (13.1) -- plus each escalated
  observation with its reason (13.2).
* **12.2 - persist the report and the full trace.** The Agent_Trace is appended
  per iteration by the loop / task 8.1 and already lives in the store; this tool
  *finalizes* it. The report is persisted as a **view** over the store's
  single-partition bundle (``get_inspection_bundle``): rather than adding a
  ``put_report`` method to the :class:`~agent.store.Store` Protocol, the tool
  writes the finalized META (status + stop_reason) and the report is thereafter
  reconstructible by id via :func:`build_report`. This keeps the Protocol
  unchanged so the DynamoDB store (task 12.2) honors the same contract -- a read
  handler rebuilds the report from the bundle without a dedicated report item.
* **12.3 - explicit zero findings.** If no finding and no escalated observation
  exist, the report still generates, with ``finding_count == 0``,
  ``escalation_count == 0``, and ``zero_findings == True`` -- an explicit record
  of zero findings, never an empty/omitted section (13.4 honesty).
* **13.4 - explicit unavailable indicators.** Any value not known at
  finalization (e.g. metrics not yet computed, or META fields never probed) is
  carried as the explicit :data:`~vision.result_schema.UNAVAILABLE` sentinel the
  store already uses, never a fabricated value.

The tool contract (so the loop can dispatch uniformly)
------------------------------------------------------

The persistence/finalization tools take the inspection id, the store, and the
loop state in addition to the decider ``arguments``. To let the loop (task 6.8)
dispatch every tool uniformly, this tool uses the signature:

    complete_inspection(store, inspection_id, state, arguments) -> InspectionReport

* ``store`` -- the injected :class:`~agent.store.Store` (``InMemoryStore`` for
  credential-free runs, DynamoDB later).
* ``inspection_id`` -- the inspection being finalized.
* ``state`` -- the :class:`~agent.state.InspectionState` the loop carried; the
  tool records the terminal :class:`~agent.state.StopReason` on it
  (``COMPLETE_INSPECTION``) so the loop observes the stop (5.3, 5.4).
* ``arguments`` -- the decider's
  :attr:`~agent.state.AgentDecision.arguments` mapping (unused today; accepted
  for a uniform dispatch signature and forward compatibility).

This module performs no OpenCV, network, or AWS work on import and is importable
with no AWS credentials (Requirement 19.4, Competition 4).
"""

from __future__ import annotations

from collections.abc import Mapping
from typing import Any, TypedDict

from agent.state import InspectionState, StopReason
from agent.store import (
    EvaluationMetrics,
    HumanReviewItem,
    InspectionBundle,
    InspectionFinding,
    InspectionRecord,
    Store,
)
from vision.result_schema import UNAVAILABLE


# --------------------------------------------------------------------------- #
# The Inspection_Report structure (design "Inspection report" / Requirement 13)
# --------------------------------------------------------------------------- #


class InspectionReport(TypedDict):
    """The structured Inspection_Report (Requirement 13, generated by 12.1).

    A JSON-serializable view assembled from the store's persisted bundle
    (findings + review queue + trace) and the finalized inspection META. It is
    deliberately a ``TypedDict`` (matching ``result_schema`` / ``store``), so it
    round-trips through the read APIs and the DynamoDB store without bespoke
    marshalling.

    Fields:

    * ``inspection_id`` -- the inspection this report summarizes (13.3).
    * ``status`` -- the finalized lifecycle status; ``"completed"`` on a normal
      finalize.
    * ``stop_reason`` -- why the loop stopped (5.4), or :data:`UNAVAILABLE` if
      the META never recorded one.
    * ``findings`` -- each :class:`~agent.store.InspectionFinding` with its
      hazard type, referenced evidence, confidence, and source timestamp
      (13.1). Empty list when there are none.
    * ``escalations`` -- each escalated observation in the Human_Review_Queue
      with its escalation reason (13.2). Empty list when there are none.
    * ``finding_count`` / ``escalation_count`` -- explicit counts.
    * ``zero_findings`` -- ``True`` iff there is no finding **and** no escalated
      observation; the explicit zero-findings record required by 12.3.
    * ``trace_length`` -- number of persisted Agent_Trace entries finalized with
      the report (12.2), so a reader can confirm the trace was persisted.
    * ``metrics`` -- the :class:`~agent.store.EvaluationMetrics`, or the explicit
      :data:`UNAVAILABLE` sentinel when none has been computed yet (13.4).
    """

    inspection_id: str
    status: str
    stop_reason: str
    findings: list[InspectionFinding]
    escalations: list[HumanReviewItem]
    finding_count: int
    escalation_count: int
    zero_findings: bool
    trace_length: int
    metrics: EvaluationMetrics | str


# --------------------------------------------------------------------------- #
# Report assembly -- a pure view over the store bundle (12.1, 12.3, 13.x)
# --------------------------------------------------------------------------- #


def build_report(bundle: InspectionBundle) -> InspectionReport:
    """Assemble an :class:`InspectionReport` from a store bundle (pure, 12.1/12.3).

    This is the single place the report shape is derived, and it is a *pure
    function* of the :class:`~agent.store.InspectionBundle` -- so the same report
    is reconstructible by any read handler (12.3) that queries the inspection
    partition, with no dedicated report item required (keeps the
    :class:`~agent.store.Store` Protocol unchanged; see module docstring).

    The report records findings (13.1), escalations with reasons (13.2), and --
    when neither exists -- an explicit zero-findings flag (12.3). Missing META /
    metrics stay the explicit :data:`UNAVAILABLE` sentinel rather than fabricated
    (13.4).
    """
    findings = list(bundle["findings"])
    escalations = list(bundle["review_queue"])

    meta = bundle["meta"]
    if isinstance(meta, Mapping):
        status = meta.get("status", UNAVAILABLE)
        stop_reason = meta.get("stop_reason", UNAVAILABLE) or UNAVAILABLE
    else:
        # meta is the UNAVAILABLE sentinel (no inspection stored) -> honest fallback.
        status = UNAVAILABLE
        stop_reason = UNAVAILABLE

    return InspectionReport(
        inspection_id=bundle["inspection_id"],
        status=status,
        stop_reason=stop_reason,
        findings=findings,
        escalations=escalations,
        finding_count=len(findings),
        escalation_count=len(escalations),
        # Explicit zero-findings record: no finding AND no escalation (12.3).
        zero_findings=(len(findings) == 0 and len(escalations) == 0),
        trace_length=len(bundle["trace"]),
        metrics=bundle["metrics"],
    )


# --------------------------------------------------------------------------- #
# The complete_inspection tool (Requirement 12)
# --------------------------------------------------------------------------- #


def complete_inspection(
    store: Store,
    inspection_id: str,
    state: InspectionState,
    arguments: Mapping[str, Any] | None = None,
) -> InspectionReport:
    """``complete_inspection`` tool: finalize the inspection (Requirement 12).

    Finalizes the Agent_Loop and generates + persists the Inspection_Report
    (12.1, 12.2):

    1. Records the terminal stop reason on ``state``
       (:attr:`~agent.state.StopReason.COMPLETE_INSPECTION`) so the loop observes
       the stop (5.3, 5.4). The first stop reason recorded wins, so if the loop
       already stopped for another reason (e.g. max iterations) that reason is
       preserved and used for the report.
    2. Reads the current bundle, then writes a finalized META back via
       :meth:`~agent.store.Store.put_inspection`: ``status="completed"``,
       ``progress=100`` (1.5), and ``stop_reason`` set to the loop's terminal
       reason. The Agent_Trace is already persisted per iteration (task 8.1);
       this tool finalizes rather than re-writing it (12.2).
    3. Re-reads the bundle and returns :func:`build_report` over it. Because the
       report is a pure view of the persisted bundle, it is retrievable later by
       id without a dedicated report item (12.3, keeps the Store Protocol
       unchanged).

    If there are no findings and no escalated observations, the returned report
    still generates with ``zero_findings=True`` and both counts ``0`` -- an
    explicit record of zero findings (12.3).

    Args:
        store: The injected durable store.
        inspection_id: The inspection to finalize (non-empty).
        state: The loop state; its terminal stop reason is recorded here.
        arguments: The decider's arguments (unused today; accepted for uniform
            loop dispatch and forward compatibility).

    Returns:
        The finalized :class:`InspectionReport`.

    Raises:
        ValueError: if ``inspection_id`` is empty. (A missing id is a programmer
            error in the loop, not decider input, so it is raised rather than
            returned as an honest-failure result.)
    """
    if not inspection_id:
        raise ValueError("complete_inspection requires a non-empty inspection_id")

    # 1) Record the terminal stop reason; first reason recorded wins (5.4).
    state.mark_stopped(StopReason.COMPLETE_INSPECTION)
    terminal_reason = (
        state.stop_reason.value
        if state.stop_reason is not None
        else StopReason.COMPLETE_INSPECTION.value
    )

    # 2) Finalize the META record (status + stop_reason + progress). We update
    #    in place when a META exists, and synthesize a minimal honest record
    #    (explicit UNAVAILABLE for never-probed fields) when it does not, so the
    #    report always has a concrete completed status to reflect (13.4).
    bundle = store.get_inspection_bundle(inspection_id)
    meta = bundle["meta"]
    if isinstance(meta, Mapping):
        finalized: InspectionRecord = dict(meta)  # type: ignore[assignment]
        finalized["status"] = "completed"
        finalized["stop_reason"] = terminal_reason
        finalized["progress"] = 100
    else:
        finalized = InspectionRecord(
            inspection_id=inspection_id,
            status="completed",
            filename=UNAVAILABLE,
            duration_ms=UNAVAILABLE,
            resolution=UNAVAILABLE,
            fps=UNAVAILABLE,
            upload_ts=UNAVAILABLE,
            progress=100,
            stop_reason=terminal_reason,
        )
    store.put_inspection(finalized)

    # 3) Re-read the finalized bundle and assemble the report view (12.1, 12.3).
    final_bundle = store.get_inspection_bundle(inspection_id)
    return build_report(final_bundle)


# --------------------------------------------------------------------------- #
# Self-validation (import-time smoke check against the in-memory store)
# --------------------------------------------------------------------------- #


def _self_check() -> None:
    """Exercise ``complete_inspection`` against a real :class:`InMemoryStore`.

    Minimal guard (no mocks), not the property/unit suite (tasks 6.10 / 6.17).
    Runs under ``python -m agent.tools.completion`` and asserts:

    * complete *with* findings + an escalation -> report lists them, counts
      match, ``zero_findings`` is False (12.1, 13.1, 13.2);
    * complete *with none* -> report explicitly records zero findings
      (``zero_findings=True``, both counts 0) (12.3);
    * status is finalized to ``"completed"`` with ``progress=100`` and the loop
      ``stop_reason`` recorded (12.1); the persisted trace length is reflected
      (12.2);
    * the report is reconstructible from the bundle by id via
      :func:`build_report` (12.3), i.e. retrievable later without a report item.
    """
    from agent.store import InMemoryStore
    from agent.trace import trace_entry
    from vision.result_schema import detection, pixel_measurement, success_result

    # -- Case A: findings + escalation (12.1, 13.1, 13.2) ------------------- #
    store: Store = InMemoryStore()
    insp = "insp-complete-A"
    store.put_inspection(
        InspectionRecord(
            inspection_id=insp,
            status="processing",
            filename="road.mp4",
            duration_ms=12000,
            resolution="1920x1080",
            fps=30.0,
            upload_ts="2026-01-01T00:00:00Z",
            progress=80,
            stop_reason=UNAVAILABLE,
        )
    )
    m = pixel_measurement(10, 20)
    before = success_result(
        method="classical", frame_ref="frame_42", source_timestamp_ms=1000,
        detections=[detection("pothole", (1, 2, 3, 4), 0.42, m)],
    )
    after = success_result(
        method="model", frame_ref="frame_42", source_timestamp_ms=1000,
        detections=[detection("pothole", (1, 2, 3, 4), 0.88, m)],
    )
    store.append_trace(insp, trace_entry(
        perception="frame_42", reasoning="low confidence", tool="analyze_frame",
        after_output=before, decision="analyze_region", ts=0,
    ))
    store.append_trace(insp, trace_entry(
        perception="frame_42 R", reasoning="corroborated", tool="analyze_region",
        before_output=before, after_output=after, decision="save_inspection_finding", ts=1,
    ))
    store.put_finding(insp, InspectionFinding(
        hazard_type="pothole", evidence_ref="evidence/insp-complete-A/frame_42.png",
        confidence=0.88, source_timestamp_ms=1000, method="model",
    ))
    store.enqueue_review(insp, HumanReviewItem(
        observation_ref="frame_99", evidence_ref="evidence/insp-complete-A/frame_99.png",
        reason="poor_input_quality", status="open",
    ))

    state_a = InspectionState()
    report_a = complete_inspection(store, insp, state_a, {})

    assert report_a["status"] == "completed", report_a
    assert report_a["stop_reason"] == StopReason.COMPLETE_INSPECTION.value
    assert state_a.stop_reason is StopReason.COMPLETE_INSPECTION
    assert report_a["finding_count"] == 1 and report_a["escalation_count"] == 1
    assert report_a["zero_findings"] is False
    # 13.1: finding carries hazard type, evidence ref, confidence, source timestamp.
    f0 = report_a["findings"][0]
    assert f0["hazard_type"] == "pothole"
    assert f0["evidence_ref"].endswith("frame_42.png")
    assert f0["confidence"] == 0.88 and f0["source_timestamp_ms"] == 1000
    # 13.2: escalation carries its reason.
    assert report_a["escalations"][0]["reason"] == "poor_input_quality"
    # 12.2: the full trace is persisted and reflected.
    assert report_a["trace_length"] == 2

    # META is finalized in the store (status + progress + stop_reason).
    meta_a = store.get_inspection_bundle(insp)["meta"]
    assert isinstance(meta_a, dict)
    assert meta_a["status"] == "completed" and meta_a["progress"] == 100
    assert meta_a["stop_reason"] == StopReason.COMPLETE_INSPECTION.value

    # 12.3-style retrievability: rebuild the report from the bundle by id alone.
    rebuilt = build_report(store.get_inspection_bundle(insp))
    assert rebuilt == report_a, "report must be a pure, reproducible view of the bundle"

    # -- Case B: zero findings and zero escalations (12.3) ------------------ #
    store_b: Store = InMemoryStore()
    insp_b = "insp-complete-B"
    store_b.put_inspection(InspectionRecord(
        inspection_id=insp_b, status="processing", filename="empty.mp4",
        duration_ms=5000, resolution="1280x720", fps=24.0,
        upload_ts="2026-01-02T00:00:00Z", progress=50, stop_reason=UNAVAILABLE,
    ))
    state_b = InspectionState()
    report_b = complete_inspection(store_b, insp_b, state_b, {})

    assert report_b["finding_count"] == 0 and report_b["escalation_count"] == 0
    assert report_b["zero_findings"] is True, "no findings/escalations must be explicit (12.3)"
    assert report_b["findings"] == [] and report_b["escalations"] == []
    assert report_b["status"] == "completed"
    assert report_b["metrics"] == UNAVAILABLE, "uncomputed metrics stay explicit UNAVAILABLE (13.4)"

    # -- Case C: preserve a prior terminal reason (e.g. max iterations) ----- #
    store_c: Store = InMemoryStore()
    insp_c = "insp-complete-C"
    store_c.put_inspection(InspectionRecord(
        inspection_id=insp_c, status="processing", filename="c.mp4",
        duration_ms=1000, resolution="640x480", fps=30.0,
        upload_ts="2026-01-03T00:00:00Z", progress=90, stop_reason=UNAVAILABLE,
    ))
    state_c = InspectionState(max_iterations=1)
    state_c.mark_stopped(StopReason.MAX_ITERATIONS)
    report_c = complete_inspection(store_c, insp_c, state_c, {})
    # First reason recorded wins: the report reflects MAX_ITERATIONS, still completed.
    assert report_c["stop_reason"] == StopReason.MAX_ITERATIONS.value
    assert report_c["status"] == "completed"

    # -- Case D: empty id is a programmer error -> raises ------------------- #
    try:
        complete_inspection(InMemoryStore(), "", InspectionState(), {})
    except ValueError:
        pass
    else:  # pragma: no cover
        raise AssertionError("complete_inspection accepted an empty inspection_id")


if __name__ == "__main__":  # pragma: no cover - manual smoke check
    _self_check()
    print(
        "[agent.tools.completion] OK: complete_inspection finalizes the inspection "
        "(status=completed, progress=100, stop_reason recorded), assembles an "
        "InspectionReport with findings (13.1) and escalations (13.2), records "
        "zero findings explicitly when none exist (12.3), reflects the persisted "
        "trace (12.2), and the report is a reproducible view of the store bundle."
    )
